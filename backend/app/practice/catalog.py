CHALLENGES = tuple(challenge for track in TRACKS for challenge in track.challenges)
CHALLENGES_BY_SLUG = {challenge.slug: challenge for challenge in CHALLENGES}


def serialize_challenge(challenge: Challenge, language: str) -> dict:
    """Возвращает контракт каталога без решения и учебного текста."""
    data = asdict(challenge)
    data["title"] = challenge.title.in_language(language)
    data["task"] = challenge.task.in_language(language)
    data["criteria"] = [item.in_language(language) for item in challenge.criteria]
    return data


def serialize_catalog(language: str) -> list[dict]:
    return [
        {
            "slug": track.slug,
            "title": track.title.in_language(language),
            "description": track.description.in_language(language),
            "challenges": [serialize_challenge(item, language) for item in track.challenges],
        }
        for track in TRACKS
    ]
