from dataclasses import asdict, dataclass


@dataclass(frozen=True)
class Text:
    ru: str
    en: str

    def in_language(self, language: str) -> str:
        return self.en if language == "en" else self.ru


@dataclass(frozen=True)
class Challenge:
    slug: str
    track: str
    difficulty: str
    title: Text
    task: Text
    target: str
    test_path: str
    criteria: tuple[Text, ...]
    markers: tuple[str, ...]


@dataclass(frozen=True)
class Track:
    slug: str
    title: Text
    description: Text
    challenges: tuple[Challenge, ...]


def _c(
    slug: str,
    track: str,
    difficulty: str,
    title_ru: str,
    title_en: str,
    task_ru: str,
    task_en: str,
    target: str,
    test_path: str,
    criteria: tuple[tuple[str, str], ...],
    markers: tuple[str, ...],
) -> Challenge:
    return Challenge(
        slug=slug,
        track=track,
        difficulty=difficulty,
        title=Text(title_ru, title_en),
        task=Text(task_ru, task_en),
        target=target,
        test_path=test_path,
        criteria=tuple(Text(ru, en) for ru, en in criteria),
        markers=markers,
    )


