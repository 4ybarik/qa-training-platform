def normalize_language(value: str | None) -> str:
    """Возвращает поддерживаемый код языка или русский по умолчанию."""
    return value if value in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def get_request_language(request: Request) -> str:
    """Определяет язык по cookie текущего запроса."""
    return normalize_language(request.cookies.get(LANGUAGE_COOKIE))


def translate(language: str, key: str, **values: object) -> str:
    """Переводит ключ и, при необходимости, подставляет именованные значения."""
    language = normalize_language(language)
    template = TRANSLATIONS[language].get(key, TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key))
    return template.format(**values) if values else template


def translator(language: str) -> Callable[..., str]:
    """Создаёт функцию ``t`` для передачи в Jinja."""
    return partial(translate, normalize_language(language))


def javascript_messages(language: str) -> dict[str, str]:
    """Возвращает только те переводы, которые нужны клиентскому JavaScript."""
    return {key: translate(language, key) for key in JAVASCRIPT_KEYS}


def localize_error(language: str, message: object) -> str:
    """Переводит известные доменные ошибки, сохраняя неизвестный текст как есть."""
    text = str(message)
    if normalize_language(language) == "en":
        return ERROR_TRANSLATIONS.get(text, text)
    return text
