"""Базовая страница — общий фундамент всех Page Object'ов.

Page Object — паттерн, при котором каждая страница (или её значимый фрагмент)
описывается классом: локаторы живут в одном месте, тесты читаются как сценарий.
Когда вёрстка меняется, правки делаются только здесь, а не в десятках тестов.

Правила хорошего тона:
- селекторы — только стабильные `data-testid` (их нарочно добавили во все
  элементы интерфейса);
- методы возвращают либо self (цепочки действий), либо новую страницу
  (переходы), либо данные;
- никаких assert внутри страниц — проверки остаются в тестах.
"""
from playwright.sync_api import Page


class BasePage:
    """Хранит page и base_url и умеет открывать свою страницу."""

    # Путь страницы внутри приложения. Переопределяется в наследниках.
    path: str = "/"

    def __init__(self, page: Page, base_url: str) -> None:
        self.page = page
        self.base_url = base_url.rstrip("/")

    @property
    def url(self) -> str:
        return f"{self.base_url}{self.path}"

    def open(self) -> "BasePage":
        """Открывает страницу и возвращает self для цепочек вызовов."""
        self.page.goto(self.url)
        return self
